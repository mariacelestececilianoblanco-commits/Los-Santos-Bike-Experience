// ==============================
// MENSAJE SIN ACTIVIDADES
// ==============================

function mostrarMensaje() {

    contenidoFanZone.className = "";

    contenidoFanZone.innerHTML = `

        <div class="sinActividades">

            <h3>Próximamente</h3>

            <p>
                Estamos preparando nuevas experiencias
                para esta fecha. ¡Mantente atento!
            </p>

        </div>

    `;

}


