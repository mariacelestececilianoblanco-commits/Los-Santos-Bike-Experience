// ==============================
// VARIABLES
// ==============================

//& Fecha y categoría seleccionadas

let fechaSeleccionada = "jueves";
let categoriaSeleccionada = "ciclistas";


// ==============================
// ELEMENTOS HTML
// ==============================

const botonesFecha = document.querySelectorAll(".btnFecha");

const botonesCategoria = document.querySelectorAll(".btnCategoria");

const contenidoFanZone = document.getElementById("contenidoFanZone");

const encabezadoTabla = document.getElementById("encabezadoTabla");

const tituloColumna2 = document.getElementById("tituloColumna2");

const tituloColumna3 = document.getElementById("tituloColumna3");


// ==============================
// CAMBIAR FECHA
// ==============================

//& Seleccionar fecha

botonesFecha.forEach(boton => {

    boton.addEventListener("click", () => {

        fechaSeleccionada = boton.dataset.fecha;

        botonesFecha.forEach(btn => {
            btn.classList.remove("activo");
        });

        boton.classList.add("activo");

        mostrarActividades();

    });

});


// ==============================
// CAMBIAR CATEGORÍA
// ==============================

//& Seleccionar categoría

botonesCategoria.forEach(boton => {

    boton.addEventListener("click", () => {

        categoriaSeleccionada = boton.dataset.categoria;

        botonesCategoria.forEach(btn => {
            btn.classList.remove("activo");
        });

        boton.classList.add("activo");

        mostrarActividades();

    });

});


// ==============================
// MOSTRAR ACTIVIDADES
// ==============================

function mostrarActividades() {

    //& Obtener actividades seleccionadas

    const actividades =
        actividadesFanZone[fechaSeleccionada][categoriaSeleccionada];

    //& Limpiar contenido anterior

    contenidoFanZone.innerHTML = "";

    //& CONCIERTOS

    if (categoriaSeleccionada === "conciertos") {

        encabezadoTabla.style.display = "none";

        contenidoFanZone.className = "gridConciertos";

        if (actividades.length === 0) {
            mostrarMensaje();
            return;
        }

        mostrarConciertos(actividades);

        return;
    }

    //& CICLISTAS

    if (categoriaSeleccionada === "ciclistas") {

        tituloColumna2.textContent = "INVITADO";

        tituloColumna3.textContent = "ACTIVIDAD";

    }

    //& EXPO MTB

    if (categoriaSeleccionada === "expo") {

        tituloColumna2.textContent = "MARCA";

        tituloColumna3.textContent = "EXHIBICIÓN";

    }

    //& Mostrar encabezado de tabla

    encabezadoTabla.style.display = "grid";

    contenidoFanZone.className = "";

    if (actividades.length === 0) {

        mostrarMensaje();

        return;

    }

    //& Mostrar contenido según categoría

    if (categoriaSeleccionada === "ciclistas") {

        mostrarCiclistas(actividades);

    } else if (categoriaSeleccionada === "expo") {

        mostrarExpo(actividades);

    }

}


// ==============================
// MOSTRAR CICLISTAS
// ==============================

function mostrarCiclistas(actividades) {

    actividades.forEach(persona => {

        const fila = document.createElement("article");

        fila.classList.add("filaFanZone");

        fila.innerHTML = `

            <img
                class="imagenInvitado"
                src="${persona.imagen}"
                alt="${persona.invitado}"
                onerror="this.style.visibility='hidden'"
            >

            <div class="horaInvitado">
                ${persona.hora}
            </div>

            <div class="nombreInvitado">
                ${persona.invitado}
            </div>

            <div class="actividadInvitado">
                ${persona.actividad}
            </div>

        `;

        contenidoFanZone.appendChild(fila);

    });

}


// ==============================
// MOSTRAR CONCIERTOS
// ==============================

function mostrarConciertos(artistas) {

    artistas.forEach(artista => {

        const tarjeta = document.createElement("article");

        tarjeta.classList.add("tarjetaConcierto");

        tarjeta.innerHTML = `

            <img
                class="imagenConcierto"
                src="${artista.imagen}"
                alt="${artista.artista}"
                onerror="this.style.visibility='hidden'"
            >

            <div class="infoConcierto">

                <div class="datoConcierto">
                    <span class="titulosCardC">Artista:</span>
                    <span class="pCardC">${artista.artista}</span>
                </div>

                <div class="datoConcierto">
                    <span  class="titulosCardC">Hora:</span>
                    <span class="pCardC">${artista.hora}</span>
                </div>

            </div>

        `;

        contenidoFanZone.appendChild(tarjeta);

    });

}


